-- Initial schema, squashed from the former V1.0 (initial tables), V1.1 (unify conversations)
-- and V1.2 (refresh tokens). It builds the FINAL structure directly, so it is meant for an
-- empty database: the old rename/backfill steps are not needed because there is no data to migrate.


-- ---------------------------------------------------------------------------------------------
-- users
-- ---------------------------------------------------------------------------------------------

create table if not exists _user
(
    id         bigint generated by default as identity primary key,
    bio        varchar(500),
    created_at timestamp(6) with time zone not null,
    email      varchar(255),
    name       varchar(100)                not null,
    password   varchar(255)                not null,
    phone      varchar(30),
    username varchar(50) not null unique,
    public_key varchar(500),
    key_backup varchar(4000)
);


-- ---------------------------------------------------------------------------------------------
-- conversation: one table for both kinds of chat (GROUP or ONE_TO_ONE)
-- ---------------------------------------------------------------------------------------------

create table if not exists conversation
(
    id               bigint generated by default as identity primary key,
    name             varchar(100),
    created_by       varchar(50)                 not null,
    created_at       timestamp(6) with time zone not null,
    chat_type        varchar(10)                 not null,
    -- "alice:bob" (the two usernames, sorted) for one-to-one chats, so each pair has exactly one; null for groups
    direct_key       varchar(101),
    -- newest message, kept up to date on every send so listing conversations needs no scan over the messages.
    -- No foreign key: messages are only ever deleted together with their conversation.
    last_message_id  bigint,
    -- sent_at of the newest message, or created_at while there is none; the conversation list is sorted by it
    last_activity_at timestamp(6) with time zone not null,

    constraint chk_conversation_type check (chat_type in ('ONE_TO_ONE', 'GROUP')),
    constraint chk_conversation_shape check (
        (chat_type = 'GROUP' and name is not null and direct_key is null)
            or (chat_type = 'ONE_TO_ONE' and name is null and direct_key is not null)),
    constraint uq_conversation_direct_key unique (direct_key)
);


-- ---------------------------------------------------------------------------------------------
-- conversation_member
-- ---------------------------------------------------------------------------------------------

create table if not exists conversation_member
(
    conversation_id bigint                      not null references conversation (id) on delete cascade,
    username        varchar(50)                 not null,
    joined_at       timestamp(6) with time zone not null,
    role            varchar(10)                 not null default 'MEMBER',
    primary key (conversation_id, username),
    constraint chk_conversation_member_role check (role in ('ADMIN', 'MEMBER'))
);

-- "my conversations": the ids come straight from the index, then the conversations are fetched by primary key
create index if not exists idx_conversation_member_username
    on conversation_member (username, conversation_id);


-- ---------------------------------------------------------------------------------------------
-- chat_message
-- ---------------------------------------------------------------------------------------------

create table if not exists chat_message
(
    id              bigint generated by default as identity primary key,
    content         text                        not null,
    -- stays set on one-to-one messages: it's bound into their ciphertext as "u:<receiver>"
    receiver        varchar(50),
    sender          varchar(50)                 not null,
    sent_at         timestamp(6) with time zone not null,
    conversation_id bigint                      not null references conversation (id) on delete cascade
);

-- a conversation's history, newest first
create index if not exists idx_msg_conversation
    on chat_message (conversation_id, sent_at desc, id desc);


-- ---------------------------------------------------------------------------------------------
-- refresh_token
-- Rotated on every use. All tokens descending from one login share a family_id, so the whole
-- line can be revoked at once (logout, or an already-used token showing up again).
-- ---------------------------------------------------------------------------------------------

create table if not exists refresh_token
(
    id         bigint generated by default as identity primary key,
    -- SHA-256 (hex) of the token; the token itself is never stored
    token_hash varchar(64)                 not null unique,
    username   varchar(50)                 not null,
    family_id  uuid                        not null,
    created_at timestamp(6) with time zone not null,
    expires_at timestamp(6) with time zone not null,
    -- set once the token has been exchanged for a new one
    rotated_at timestamp(6) with time zone
);

create index if not exists idx_refresh_token_family on refresh_token (family_id);

-- periodic cleanup of expired tokens
create index if not exists idx_refresh_token_expires on refresh_token (expires_at);