create table if not exists _user
(
    id         bigint generated by default as identity primary key,
    bio        varchar(500),
    created_at timestamp(6) with time zone not null,
    email      varchar(255),
    name       varchar(100)                not null,
    password   varchar(255)                not null,
    phone      varchar(30),
    username   varchar(50) unique not null,
    public_key varchar(500),
    key_backup varchar(4000)
);


create table if not exists chat_group
(
    id         bigint generated by default as identity primary key,
    name       varchar(100)                not null,
    created_by varchar(50)                 not null,
    created_at timestamp(6) with time zone not null
);


create table if not exists chat_message
(
    id       bigint generated by default as identity primary key,
    content  text not null,
    receiver varchar(50),
    group_id bigint references chat_group (id) on delete cascade,
    sender   varchar(50)                 not null,
    sent_at  timestamp(6) with time zone not null
);

alter table chat_message
    add constraint chk_msg_target check ((receiver is null) <> (group_id is null));

create index if not exists idx_msg_sender_receiver
    on chat_message (sender, receiver, sent_at);

create index if not exists idx_msg_receiver
    on chat_message (receiver, sent_at);

create index idx_msg_group on chat_message (group_id, sent_at);


create table if not exists group_member
(
    group_id  bigint                      not null references chat_group (id) on delete cascade,
    username  varchar(50)                 not null,
    joined_at timestamp(6) with time zone not null,
    role      varchar(10)                 not null default 'MEMBER',
    primary key (group_id, username)
);

create index if not exists idx_group_member_username on group_member (username);

alter table group_member
    add constraint chk_group_member_role check (role in ('ADMIN', 'MEMBER'));